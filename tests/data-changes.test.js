// ==================== 容配比全量汇总 ====================
describe('容配比数据格式', () => {
  it('所有 r 值均为合法形式（空 / 标准x / 不超配x）', () => {
    // 原为"总变更数 = 17"的恒真断言（非空数 + 空数恒等于总数，任何数据都能通过）。
    // 改为校验取值域：新增非法形式（如拼写变体、多余空白）时失败。
    const valid = /^(|标准\d+(?:\.\d+)?|不超配\d+(?:\.\d+)?)$/;
    const bad = Object.entries(REGION_DB)
      .filter(([, v]) => !valid.test(v.r))
      .map(([k, v]) => `${k}: "${v.r}"`);
    expect(bad).toEqual([]);
  });
});
